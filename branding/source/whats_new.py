"""Builds WhatsNewData.lua (the in-game What's new window) from CHANGELOG.md.

    python branding/source/whats_new.py <codexDir>

The game can't read CHANGELOG.md, so its newest sections go into Lua: ns.WHATS_NEW = { { version, items }, ... },
newest first, the "Unreleased" section included (shown only by /codex whatsnew in a development copy). Run it after
every CHANGELOG change and before a release tag (the release-addons skill does); codex_test.lua fails when the file
is out of date. Markdown kept as it is apart from the leading "- "; Lua turns **bold** into the accent colour.
"""
import os
import re
import sys

KEEP = 8  # released sections kept


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sections(changelog):
    found, current = [], None
    for line in changelog.splitlines():
        heading = re.match(r"^##\s+(.+?)\s*$", line)
        if heading:
            current = {"version": heading.group(1), "items": []}
            found.append(current)
        elif current is not None and line.startswith("- "):
            current["items"].append(line[2:].strip())
        elif current is not None and line.startswith("  ") and current["items"]:
            current["items"][-1] += " " + line.strip()  # a wrapped bullet
    return found


def build(codex_dir):
    with open(os.path.join(codex_dir, "CHANGELOG.md"), encoding="utf-8") as f:
        found = sections(f.read())
    unreleased = [s for s in found if s["version"].lower() == "unreleased"]
    released = [s for s in found if s["version"].lower() != "unreleased"][:KEEP]
    out = ["local addonName, ns = ...", "",
           "-- Generated by branding/source/whats_new.py from CHANGELOG.md: do not edit by hand.",
           "ns.WHATS_NEW = {"]
    for section in unreleased + released:
        if not section["items"]:
            continue
        out.append("  { version = %s, items = {" % lua_string(section["version"]))
        for item in section["items"]:
            out.append("    %s," % lua_string(item))
        out.append("  } },")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    codex = sys.argv[1] if len(sys.argv) > 1 else "."
    with open(os.path.join(codex, "WhatsNewData.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write(build(codex))
    print("WhatsNewData.lua written")
